function resolveText(ctx) {
  let language = "zh";
  try {
    const locale = String(ctx && typeof ctx.getEnv === "function" ? ctx.getEnv("LANG") || "" : "").toLowerCase();
    if (locale.startsWith("en")) language = "en";
  } catch (_) {}
  return TEXT[language];
}

